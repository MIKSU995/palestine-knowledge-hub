    function copyToClipboard(val, btn) {
        navigator.clipboard.writeText(val).then(() => {
            const orig = btn.innerText;
            btn.innerText = '✅ Tersalin';
            btn.classList.add('bg-red-600');
            setTimeout(() => {
                btn.innerText = orig;
                btn.classList.remove('bg-red-600');
            }, 2000);
        });
    }

