            const btnText = document.getElementById('copy-btn-text');
            if(btnText) {
                btnText.innerText = '✅ Pesan Berhasil Disalin!';
                setTimeout(() => { btnText.innerText = 'Salin Pesan Solidaritas'; }, 2500);
            }
        });
    }
